package kapi.core.auto

/**
 * 账单自动分类。
 *
 * ## 为什么放在 `core` 而不是 app
 *
 * 它是纯逻辑：输入商户名和账单原文，输出一个分类路径。放 `core` 才有单测能钉住——
 * 而这一块**必须**有单测，因为它决定的是"这笔钱记到哪一栏"。分类错了金额还是对的，
 * 用户月底看某一栏的数字对不上，却不会知道是自动分错了。
 *
 * ## 为什么要两级
 *
 * 原来只有 11 个平铺的顶级分类。`餐饮` 下面什么都不分，意味着包子铺和火锅在统计里
 * 长得一样——但这两笔在用户的生活里根本不是一回事。`购物` 更极端：一件 T 恤和一台
 * 显示器放在同一栏里，这栏数字没有任何意义。
 *
 * 顶级分类保持不变（已有的库里有 `cat-0`…`cat-10`，改名会打断用户的数据），
 * 细分类挂在它们下面，用 `parentId` 串起来。
 *
 * ## 匹配顺序
 *
 * ```
 * 1. 商户名     ← 最可靠。包子铺、火锅店、星巴克、滴滴，这些名字本身就是分类
 * 2. 账单原文   ← 商户名不认识时的兜底。商品标题在这里面
 * ```
 *
 * 商户名优先是刻意的。支付宝那笔 `微雪**店 / ESP32-P4开发板`：商户名 `微雪` 谁也
 * 不认识，但原文里的 `开发板` 指向数码。**而淘宝那种"某某旗舰店"名字毫无信息量的
 * 情形，恰恰只能靠商品标题。** 所以两个都要看，商户名优先。
 *
 * ## 规则表是**有序**的，命中第一条就返回
 *
 * 不是"所有规则都跑一遍投票"。投票会让一个具体规则被宽泛规则稀释——
 * `星巴克` 应当是"咖啡茶饮"，可它同时也含 `餐`，而"餐"在"正餐"那条里。
 * 投票的话这两条会打架，结果不可预测。**有序 + 具体在前**，行为可解释、可测试。
 */
