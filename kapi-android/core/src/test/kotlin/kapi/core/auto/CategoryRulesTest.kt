package kapi.core.auto

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/**
 * 自动分类的回归。
 *
 * ## 用例全部来自真机原文，不是编的
 *
 * 商户名和商品标题都取自 2026-10-01 realme RMX3852 上实际抓到的账单详情页
 * （原文见 `docs/微信读屏方案.md`）。编出来的商户名（比如"测试商户"）会让规则表
 * 看起来很准，而真机上的真实名字往往又长又脏——`微雪**店`、`转账-转给橘生`。
 */
class CategoryRulesTest {

    private fun exp(merchant: String?, raw: String? = null) =
        CategoryRules.classify(merchant, raw, income = false)

    private fun inc(merchant: String?, raw: String? = null) =
        CategoryRules.classify(merchant, raw, income = true)

    // ------------------------------------------------------------ 餐饮

    @Test
    fun `包子铺归到餐饮的早餐`() {
        assertEquals("餐饮/早餐", exp("张记包子铺")?.text)
        assertEquals("餐饮/早餐", exp("早阳包子")?.text)
        assertEquals("餐饮/早餐", exp("永和大王豆浆油条")?.text)
    }

    @Test
    fun `火锅归到餐饮的火锅`() {
        assertEquals("餐饮/火锅", exp("海底捞")?.text)
        assertEquals("餐饮/火锅", exp("川西坝子火锅")?.text)
        assertEquals("餐饮/火锅", exp("杨国福麻辣烫")?.text)
    }

    @Test
    fun `咖啡奶茶是独立的一档，不混进正餐`() {
        assertEquals("餐饮/咖啡茶饮", exp("星巴克")?.text)
        assertEquals("餐饮/咖啡茶饮", exp("瑞幸咖啡")?.text)
        assertEquals("餐饮/咖啡茶饮", exp("蜜雪冰城")?.text)
    }

    /**
     * 「餐」是个宽泛词，很容易把咖啡奶茶拖进正餐。
     * 具体规则必须排在它前面——这正是规则表**有序**的原因。
     */
    @Test
    fun `具体的规则不会被宽泛的字吃掉`() {
        // 星巴克含"客"不含"餐"，但"瑞幸咖啡店"含"店"；
        // 用一个同时含"餐"的名字验证具体规则优先。
        assertEquals("餐饮/早餐", exp("早餐餐厅")?.text)
        assertEquals("餐饮/火锅", exp("火锅餐厅")?.text)
    }

    @Test
    fun `外卖只从商户名认，不从商品标题认`() {
        assertEquals("餐饮/外卖", exp("美团外卖")?.text)
        // 商品标题里的"外卖"常常只是套餐名的一部分
        assertEquals("餐饮/正餐", exp("某饭店", "黄焖鸡米饭外卖套餐 28.00")?.text)
    }

    // ------------------------------------------------------------ 购物

    /**
     * 这一条是整个功能存在的理由。
     *
     * 支付宝真机原文：商户 `微雪**店`，商品标题
     * `微雪 ESP32-P4开发板 支持WIFI6和蓝牙5 4.3寸触控屏幕小智AI语音`。
     *
     * `微雪**店` 这个名字**不含任何品类信息**——它就是个店名。
     * 真正能判出"数码"的是商品标题里的 `开发板`。
     * 只看商户名的分类器在这一笔上必然放弃。
     */
    @Test
    fun `购物按商品标题判品类，而不是按店名`() {
        val alipay = "账单详情\n返回\n对此订单有疑问\n往来流水证明\n查看往来记录\n" +
            "添加\n备注\n开关\n计入收支\n买软件\n为您推荐\n请选择\n标签\n数码电器\n" +
            "账单分类\n我的消费图鉴\n账单管理\n更多\n共1件\n" +
            "微雪 ESP32-P4开发板 支持WIFI6和蓝牙5 4.3寸触控屏幕小智AI语音\nO1CN012PMIq41QBehQyMbEP_!!2206714651938\n" +
            "交易详情\n已领取14积分\n支付奖励\n交通银行信用卡(5894)\n付款方式\n" +
            "2026-09-29 16:03:25\n2026-09-29 16:03:25\n支付时间\n-1.98\n交通银行立减金\n" +
            "极速付款\n管理极速付款\n等待确认收货\n支出244.93元\n微雪**店"
        assertEquals("购物/数码", exp("微雪**店", alipay)?.text)
    }

    @Test
    fun `服饰和数码是两回事`() {
        assertEquals("购物/服饰", exp("优衣库")?.text)
        assertEquals("购物/服饰", exp("某店", "纯棉短袖T恤 男款 夏季薄款")?.text)
        assertEquals("购物/数码", exp("某店", "无线蓝牙耳机 降噪 入耳式")?.text)
        assertEquals("购物/数码", exp("小米之家")?.text)
        assertEquals("购物/家电", exp("某店", "滚筒洗衣机 10公斤")?.text)
        assertEquals("购物/美妆", exp("某店", "烟酰胺精华液 30ml")?.text)
    }

    // ------------------------------------------------------------ 交通

    @Test
    fun `交通按出行方式细分`() {
        assertEquals("交通/打车", exp("滴滴出行")?.text)
        assertEquals("交通/公共交通", exp("地铁乘车码")?.text)
        assertEquals("交通/加油", exp("中国石化加油站")?.text)
        assertEquals("交通/停车", exp("万达停车场")?.text)
    }

    /**
     * 「行」不能当交通的关键词。
     *
     * `交通银行信用卡(5894)` 出现在**几乎每一笔**微信/支付宝账单里，
     * 而商户名 `深圳市腾讯计算机系统有限公司` 也是「行」字结尾。
     * 交通那条兜底规则是 `车/行/驾/票` 时，真机上一笔数码购物
     * （`微雪**店 / ESP32-P4开发板`）和一笔腾讯文档自动续费都被它抢走，
     * 全部记成了"交通"。
     *
     * 判不出来宁可留未分类——那比"记成交通"诚实。
     */
    @Test
    fun `交通银行不能被当成交通`() {
        assertNull(exp("中国银行", "中国银行储蓄卡(0416)\n付款方式"))
        assertNull(exp("深圳市腾讯计算机系统有限公司", "深圳市腾讯计算机系统有限公司\n商户全称"))
    }

    /**
     * 短中文词会**跨词边界**命中不相干的词。
     *
     * 微信账单详情页上有一行 `商家电话`——商**家电**话。规则表里当时有
     * 一个 `家电` 关键词，`contains("家电")` 直接命中，一笔腾讯文档自动续费
     * 被抢成「购物/家电」。
     *
     * 和「交通银行」那个坑是同一类：**越短的词越危险**，而中文没有词边界。
     * 加词之前先拿真机原文 `grep` 一遍，比想清楚更可靠。
     */
    @Test
    fun `商家电话里的家电不能命中家电规则`() {
        assertNull(exp("深圳市腾讯计算机系统有限公司", "商家电话\n联系商家\n申请电子凭证"))
    }

    // ------------------------------------------------------------ 真机样本

    /**
     * 微信商家账单详情页真机原文。
     *
     * 商户 `深圳市腾讯计算机系统有限公司` 完全看不出是什么业务，
     * 商品 `腾讯文档超级会员业务自动续费31天` 才是判据——
     * 一笔**自动续费**的订阅，归到「娱乐/会员」。
     */
    @Test
    fun `微信商家账单：腾讯文档自动续费归到会员`() {
        val wechat = "加载中\n本服务由财付通提供\n公众号\n商家电话\n联系商家\n申请电子凭证\n" +
            "管理扣费服务\n在此商户的交易\n对订单有疑惑\n账单服务\n" +
            "product_SZ_2025080856740368\n商户单号\n42000028202508080433683194\n交易单号\n" +
            "中国银行储蓄卡(0414)\n付款方式\n财付通支付科技有限公司\n收单机构\n" +
            "深圳市腾讯计算机系统有限公司\n商户全称\n腾讯文档超级会员业务自动续费31天\n商品\n" +
            "2025年8月8日 09:24:15\n支付时间\n支付成功\n当前状态\n-18.00\n深圳市腾讯计算机系统有限公司"
        assertEquals("娱乐/会员", exp("深圳市腾讯计算机系统有限公司", wechat)?.text)
    }

    /**
     * 微信 P2P 转账。
     *
     * 商户 `转账-转给橘生`、原文里没有任何品类信息——这是**判不出来**的。
     * 宁可留「未分类」让用户两秒改掉，也不要塞进「人情」或「其他」——
     * 塞错了用户不会发现，而未分类他一眼就知道要自己管。
     */
    @Test
    fun `私人转账判不出来时留空，不硬塞一档`() {
        val raw = "加载中\n本服务由财付通提供\n查看往来转账\n定位到聊天位置\n对订单有疑惑\n" +
            "账单服务\n1000050001202610010626797537039\n转账单号\n中国银行储蓄卡(0414)\n支付方式\n" +
            "2026年10月1日 14:45:40\n转账时间\n微信转账\n转账说明\n提醒对方收款\n" +
            "等待对方确认收钱\n当前状态\n-0.10\n转账-转给橘生"
        assertNull(exp("转账-转给橘生", raw))
    }

    // ------------------------------------------------------------ 收入

    @Test
    fun `收入走另一套词表`() {
        assertEquals("工资", inc("某某科技有限公司", "9月工资")?.text)
        assertEquals("报销", inc("差旅报销")?.text)
        assertEquals("理财", inc("零钱通收益")?.text)
    }

    /**
     * 「红包」在支出侧是人情，在收入侧是钱进来了——**方向不同，归档就不同**。
     * 这条钉住的是两套词表必须分开维护，而不是合并成一张。
     */
    @Test
    fun `同一个词在收入和支出下归档不同`() {
        assertEquals("人情/红包", exp("微信红包")?.text)
        assertEquals("红包", inc("微信红包")?.text)
    }

    // ------------------------------------------------------------ 占位与脏数据

    @Test
    fun `占位商户名不参与判定`() {
        // 解析器在读不到商户时会填这些，它们不是商户名
        assertNull(exp("（没读到商户）", "支出10.1元"))
        assertNull(exp(null, null))
        assertNull(exp("", ""))
    }

    /**
     * `加载中` 这种占位行**不能**被当成商户名去匹配。
     *
     * 2026-10-01 真机：支付宝那一屏还没稳定就抓了，`merchant="加载中"`。
     * 拿它去匹配规则没直接出事（它不含品类词），但兜底到原文时命中了
     * 餐饮那条 `餐` 的兜底——支付宝详情页上有 `餐饮美食` 分类筛选器——
     * 于是一笔判不出是什么的支付被记成了"餐饮"。
     */
    @Test
    fun `加载中这类占位行不参与判定`() {
        assertNull(exp("加载中", "餐饮美食\n账单分类\n支出3.99元\n交易成功"))
    }

    /** 餐饮不留 `餐/饮` 兜底——具体的餐厅/火锅/咖啡/外卖各有一条。 */
    @Test
    fun `判不出餐饮时不靠一个字硬凑`() {
        assertNull(exp("某不知名商户", "餐饮美食\n支出3.99元"))
    }

    @Test
    fun `判不出来就返回 null 而不是猜一档`() {
        assertNull(exp("某某某某有限公司", "订单编号 ABC123 状态 已完成"))
    }

    // ---------------------------------------------------------- 2026-10-02 真机样本

    /** 好医保页（mcode dump 20）：商品「2026.9月保费缴清-好医保…」，页面分类值「保险」。 */
    @Test
    fun `保险归到医疗，好医保也不例外`() {
        assertEquals(
            "医疗/保险",
            exp("中国人民健康保险股份有限公司", "2026.9月保费缴清-好医保·长期医疗(旗舰版2026)-**娜\n交易详情\n保险\n账单分类")?.text,
        )
    }

    /** NYCD 皮带轮页（dump 05/06）：此前整页判 null；页面分类值「家居家装」。 */
    @Test
    fun `家居家装值命中购物家居`() {
        assertEquals(
            "购物/家居",
            exp("ny**店", "NYCD非标同步轮定制3m5m8m现货皮带轮AF/AS/BF同步带轮定做铝合金\n共1件\n家居家装\n账单分类")?.text,
        )
    }

    /** TP-LINK 页（dump 17）：页面分类值「日用百货」，且不能被更晚的闲鱼平台规则抢走。 */
    @Test
    fun `日用百货命中日用，闲鱼规则排在它后面`() {
        assertEquals(
            "日用",
            exp("x***7", "支出55元\n等待确认收货\n闲鱼100元以下免密支付\nTP-LINK TL-IPC43AN-4 300万云台无线网\n商品说明\n日用百货\n账单分类")?.text,
        )
    }

    /** 先用后付页（dump 11）：rawText 含商户行（整屏文字），商户名里的「淘宝」兜底成购物。 */
    @Test
    fun `淘宝是平台兜底，排在具体品类词之后`() {
        assertEquals(
            "购物",
            exp("杭州淘宝通信技术有限公司", "杭州淘宝通信技术有限公司\n支出10.1元\n商品说明\n先用后付\n商业服务\n账单分类")?.text,
        )
        // 平台兜底不抢具体品类：淘宝上买的耳机仍是数码（商户轮跳过平台词）
        assertEquals("购物/数码", exp("杭州淘宝通信技术有限公司", "杭州淘宝通信技术有限公司\n蓝牙耳机\n商品说明")?.text)
        // 闲鱼单独一档
        assertEquals("购物/二手", exp(null, "闲鱼\n对方账户\n支出55元")?.text)
    }

    /**
     * 品牌词（2026-10-02 用户指认：小佩是宠物品牌 PETKIT）。
     * 关键是**不靠页面角标**：夹具里没有「宠物」二字，商户名自己就能归对——
     * 页面自带的分类值（账单分类/推荐位）不是每屏都有。
     */
    @Test
    fun `宠物品牌只凭商户名归档，不依赖页面角标`() {
        assertEquals("购物/宠物", exp("小佩网络科技（上海）有限公司")?.text)
        assertEquals("购物/宠物", exp("PETKIT旗舰店", "智能喂食器\n商品说明")?.text)
        assertEquals("购物/宠物", exp("波奇宠物商城")?.text)
    }
}
